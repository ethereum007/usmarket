-- Runner Engine PR1-PR3: minute features, TOD baselines and diagnostics.
-- Designed for batched upserts; raw ticks are intentionally not stored.

create table if not exists public.runner_minute_features (
    id bigint generated by default as identity primary key,
    session_date date not null,
    symbol text not null,
    exchange text not null default 'NSE',
    minute_timestamp timestamptz not null,
    timestamp timestamptz not null,
    source_timestamp timestamptz not null,
    processing_timestamp timestamptz not null,
    minute_of_session smallint not null check (minute_of_session >= 0 and minute_of_session <= 375),
    ltp double precision not null,
    ret_1m double precision, ret_3m double precision, ret_5m double precision,
    ret_10m double precision, ret_15m double precision, ret_30m double precision,
    ret_from_open double precision, ret_from_prev_close double precision,
    return_z_1m double precision, return_z_5m double precision, return_z_15m double precision,
    rvol_tod_20d double precision, rvol_tod_60d double precision,
    rvol_tod_z_20d double precision, rvol_tod_z_60d double precision,
    volume_percentile_20d double precision, volume_percentile_60d double precision,
    rvol_1m double precision, rvol_3m double precision, rvol_5m double precision,
    rvol_10m double precision, rvol_15m double precision,
    volume_velocity_1m double precision, volume_velocity_3m double precision,
    volume_velocity_5m double precision, volume_acceleration double precision,
    turnover double precision, turnover_velocity double precision,
    current_intraday_range double precision, range_tod_ratio double precision,
    range_expansion double precision, atr_normalized_move double precision,
    vwap double precision, above_vwap boolean, distance_vwap_pct double precision, vwap_slope double precision,
    pdh double precision, pdl double precision, distance_pdh_pct double precision, distance_pdl_pct double precision,
    pdh_break boolean, pdl_break boolean,
    orb15_break_high boolean, orb15_break_low boolean, orb30_break_high boolean, orb30_break_low boolean,
    distance_20d_high_pct double precision, distance_50d_high_pct double precision,
    at_20d_high boolean, at_50d_high boolean, day_range_location double precision, close_location_value double precision,
    sector text, sector_return double precision, sector_relative_strength double precision, sector_rank integer,
    market_return double precision, market_above_vwap boolean, market_breadth double precision, market_regime text,
    spread_bps double precision, depth_metadata jsonb,
    abnormal_score double precision, accumulation_score double precision, institutional_score double precision,
    market_pulse text, cpr_metadata jsonb, vcp_metadata jsonb,
    data_source text not null, data_quality jsonb not null default '[]'::jsonb,
    freshness_seconds double precision not null, feature_version text not null,
    created_at timestamptz not null default now(), updated_at timestamptz not null default now(),
    unique (session_date, symbol, minute_timestamp, feature_version)
);

create index if not exists runner_minute_features_date_ts_idx on public.runner_minute_features (session_date, minute_timestamp desc);
create index if not exists runner_minute_features_symbol_ts_idx on public.runner_minute_features (symbol, minute_timestamp desc);
create index if not exists runner_minute_features_version_date_idx on public.runner_minute_features (feature_version, session_date desc);

create table if not exists public.runner_baseline_stats (
    id bigint generated by default as identity primary key,
    symbol text not null,
    minute_of_session smallint not null check (minute_of_session >= 0 and minute_of_session <= 375),
    lookback_sessions smallint not null check (lookback_sessions > 0),
    metric text not null,
    median double precision, mean double precision, std double precision,
    percentiles jsonb not null default '{}'::jsonb,
    as_of_date date not null,
    baseline_version text not null,
    sample_count smallint not null default 0,
    created_at timestamptz not null default now(), updated_at timestamptz not null default now(),
    unique (symbol, minute_of_session, lookback_sessions, metric, baseline_version)
);

create index if not exists runner_baseline_symbol_minute_idx on public.runner_baseline_stats (symbol, minute_of_session, lookback_sessions);
create index if not exists runner_baseline_version_date_idx on public.runner_baseline_stats (baseline_version, as_of_date desc);

create table if not exists public.runner_state_events (
    id bigint generated by default as identity primary key,
    session_date date not null,
    event_timestamp timestamptz not null,
    symbol text not null,
    from_state text, to_state text, reason text,
    feature_version text, metadata jsonb not null default '{}'::jsonb,
    created_at timestamptz not null default now()
);
create index if not exists runner_state_events_symbol_ts_idx on public.runner_state_events (symbol, event_timestamp desc);

create table if not exists public.runner_data_quality_events (
    id bigint generated by default as identity primary key,
    session_date date not null,
    event_timestamp timestamptz not null,
    symbol text,
    quality_state text not null,
    primary_provider text, secondary_provider text,
    details jsonb not null default '{}'::jsonb,
    created_at timestamptz not null default now()
);
create index if not exists runner_quality_date_state_idx on public.runner_data_quality_events (session_date, quality_state, event_timestamp desc);

create table if not exists public.runner_engine_runs (
    run_id uuid primary key,
    run_type text not null,
    status text not null,
    universe text,
    started_at timestamptz not null,
    completed_at timestamptz,
    symbols_processed integer not null default 0,
    symbols_failed integer not null default 0,
    rows_persisted integer not null default 0,
    metadata jsonb not null default '{}'::jsonb,
    created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);

create or replace function public.set_runner_updated_at()
returns trigger
language plpgsql
set search_path = public
as $$
begin
    new.updated_at = now();
    return new;
end;
$$;

drop trigger if exists runner_minute_features_updated_at on public.runner_minute_features;
create trigger runner_minute_features_updated_at before update on public.runner_minute_features
for each row execute function public.set_runner_updated_at();

drop trigger if exists runner_baseline_stats_updated_at on public.runner_baseline_stats;
create trigger runner_baseline_stats_updated_at before update on public.runner_baseline_stats
for each row execute function public.set_runner_updated_at();

drop trigger if exists runner_engine_runs_updated_at on public.runner_engine_runs;
create trigger runner_engine_runs_updated_at before update on public.runner_engine_runs
for each row execute function public.set_runner_updated_at();

