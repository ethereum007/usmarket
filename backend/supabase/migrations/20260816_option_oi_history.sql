CREATE TABLE IF NOT EXISTS public.option_oi_snapshots (
  id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  bucket_at               TIMESTAMPTZ NOT NULL,
  captured_at             TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  index_key               TEXT NOT NULL,
  underlying              TEXT NOT NULL,
  expiry                  TEXT NOT NULL,
  scope                   TEXT NOT NULL CHECK (scope IN ('overall', 'strike')),
  strike_price            NUMERIC(12, 2) NOT NULL DEFAULT 0,
  spot_price              NUMERIC(14, 4),
  spot_change_pct         NUMERIC(12, 4),
  call_oi                 BIGINT NOT NULL DEFAULT 0,
  put_oi                  BIGINT NOT NULL DEFAULT 0,
  total_oi                BIGINT NOT NULL DEFAULT 0,
  call_oi_change          BIGINT NOT NULL DEFAULT 0,
  put_oi_change           BIGINT NOT NULL DEFAULT 0,
  total_oi_change         BIGINT NOT NULL DEFAULT 0,
  net_oi                  BIGINT NOT NULL DEFAULT 0,
  net_oi_change           BIGINT NOT NULL DEFAULT 0,
  pcr                     NUMERIC(12, 4),
  call_ltp                NUMERIC(14, 4),
  put_ltp                 NUMERIC(14, 4),
  call_ltp_change_pct     NUMERIC(12, 4),
  put_ltp_change_pct      NUMERIC(12, 4),
  call_action             TEXT NOT NULL DEFAULT 'BASELINE',
  put_action              TEXT NOT NULL DEFAULT 'BASELINE',
  change_direction        TEXT NOT NULL CHECK (change_direction IN ('BULLISH', 'BEARISH', 'NEUTRAL')),
  change_label            TEXT NOT NULL,
  change_reason           TEXT NOT NULL,
  source                  TEXT NOT NULL DEFAULT 'unknown',
  created_at              TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT option_oi_snapshots_scope_strike_check CHECK (
    (scope = 'overall' AND strike_price = 0)
    OR (scope = 'strike' AND strike_price > 0)
  ),
  CONSTRAINT option_oi_snapshots_bucket_unique UNIQUE (
    index_key, expiry, bucket_at, scope, strike_price
  )
);

COMMENT ON TABLE public.option_oi_snapshots IS
  'Alpha Radar service-only five-minute OI snapshots; one overall row and one row per strike.';
COMMENT ON COLUMN public.option_oi_snapshots.change_reason IS
  'Positioning evidence derived from five-minute OI and premium changes; not a claim of market causation.';

CREATE INDEX IF NOT EXISTS idx_option_oi_snapshots_lookup
  ON public.option_oi_snapshots(index_key, expiry, bucket_at DESC);
CREATE INDEX IF NOT EXISTS idx_option_oi_snapshots_strike_lookup
  ON public.option_oi_snapshots(index_key, expiry, strike_price, bucket_at DESC)
  WHERE scope = 'strike';
CREATE INDEX IF NOT EXISTS idx_option_oi_snapshots_retention
  ON public.option_oi_snapshots(bucket_at);

ALTER TABLE public.option_oi_snapshots ENABLE ROW LEVEL SECURITY;

-- The browser must use the Alpha Radar API. No direct anon/authenticated access.
REVOKE ALL ON TABLE public.option_oi_snapshots FROM anon, authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE public.option_oi_snapshots TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.option_oi_snapshots_id_seq TO service_role;
