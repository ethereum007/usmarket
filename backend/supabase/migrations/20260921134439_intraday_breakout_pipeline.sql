-- Intraday retracement-breakout pipeline.
-- Only completed 5-minute candles are stored. Fifteen-minute candles are
-- derived from those rows so the same market observation is never duplicated.

create table if not exists public.intraday_candles (
    id bigint generated by default as identity primary key,
    session_date date not null,
    symbol text not null,
    exchange text not null default 'NSE',
    timeframe_minutes smallint not null default 5 check (timeframe_minutes = 5),
    bar_start timestamptz not null,
    open double precision not null check (open > 0),
    high double precision not null check (high > 0),
    low double precision not null check (low > 0),
    close double precision not null check (close > 0),
    volume bigint not null default 0 check (volume >= 0),
    source text not null,
    source_bar_count smallint not null default 1 check (source_bar_count > 0),
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    constraint intraday_candles_valid_ohlc check (
        high >= greatest(open, low, close)
        and low <= least(open, high, close)
    ),
    unique (session_date, symbol, timeframe_minutes, bar_start)
);

create index if not exists intraday_candles_session_symbol_idx
    on public.intraday_candles (session_date, symbol, bar_start);

create table if not exists public.intraday_breakout_signals (
    id bigint generated by default as identity primary key,
    session_date date not null,
    symbol text not null,
    exchange text not null default 'NSE',
    signal_type text not null check (
        signal_type in ('FIVE_MIN_BREAKOUT', 'FIFTEEN_MIN_BREAKOUT', 'PREVIOUS_DAY_HIGH_BREAK')
    ),
    timeframe_minutes smallint not null check (timeframe_minutes in (0, 5, 15)),
    signal_time timestamptz not null,
    trigger_price double precision not null check (trigger_price > 0),
    prior_intraday_high double precision,
    previous_day_high double precision,
    retracement_bar_start timestamptz,
    radar_score integer,
    radar_quality text,
    definition_version text not null default 'intraday-retracement-v1',
    metadata jsonb not null default '{}'::jsonb,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    constraint intraday_signal_timeframe_matches_type check (
        (signal_type = 'FIVE_MIN_BREAKOUT' and timeframe_minutes = 5)
        or (signal_type = 'FIFTEEN_MIN_BREAKOUT' and timeframe_minutes = 15)
        or (signal_type = 'PREVIOUS_DAY_HIGH_BREAK' and timeframe_minutes = 0)
    ),
    unique (session_date, symbol, signal_type)
);

create index if not exists intraday_breakout_signals_session_time_idx
    on public.intraday_breakout_signals (session_date, signal_time desc);

create or replace function public.set_intraday_updated_at()
returns trigger
language plpgsql
set search_path = public
as $$
begin
    new.updated_at = now();
    return new;
end;
$$;

drop trigger if exists intraday_candles_updated_at on public.intraday_candles;
create trigger intraday_candles_updated_at
before update on public.intraday_candles
for each row execute function public.set_intraday_updated_at();

drop trigger if exists intraday_breakout_signals_updated_at on public.intraday_breakout_signals;
create trigger intraday_breakout_signals_updated_at
before update on public.intraday_breakout_signals
for each row execute function public.set_intraday_updated_at();

alter table public.intraday_candles enable row level security;
alter table public.intraday_breakout_signals enable row level security;

-- These are backend-owned market-data tables. The premium API performs the
-- subscription check and reads them with the server-only service role.
revoke all on table public.intraday_candles from anon, authenticated;
revoke all on table public.intraday_breakout_signals from anon, authenticated;
grant select, insert, update, delete on table public.intraday_candles to service_role;
grant select, insert, update, delete on table public.intraday_breakout_signals to service_role;
grant usage, select on sequence public.intraday_candles_id_seq to service_role;
grant usage, select on sequence public.intraday_breakout_signals_id_seq to service_role;
