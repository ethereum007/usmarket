def resolve_universe(universe: str = "nifty200", limit: int | None = None) -> list[str]:
    """Return a deterministic symbol list for backend warmers and scanners."""
    universe_key = (universe or "nifty200").strip().lower()
    if universe_key in {"nifty50", "n50"}:
        symbols = NIFTY50
    elif universe_key in {"nifty100", "n100"}:
        symbols = NIFTY100_STOCKS
    elif universe_key in {"nifty500", "n500"}:
        symbols = NIFTY500_STOCKS
    elif universe_key in {"smallcap", "sc250", "smallcap250"}:
        symbols = SMALLCAP_250_STOCKS
    elif universe_key in {"microcap", "micro", "micro_watch"}:
        symbols = MICROCAP_WATCH_STOCKS
    elif universe_key in {"broad", "all", "research"}:
        symbols = BROAD_RESEARCH_STOCKS
    else:
        symbols = NIFTY200_STOCKS

    if limit is None:
        return list(symbols)
    cap = max(1, int(limit))
    return list(symbols[:cap])
