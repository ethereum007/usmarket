def _dedupe(symbols: list[str]) -> list[str]:
    out: list[str] = []
    seen: set[str] = set()
    for symbol in symbols:
        clean = str(symbol or "").strip().upper()
        if clean and clean not in seen:
            out.append(clean)
            seen.add(clean)
    return out


